CREATE TABLE IF NOT EXISTS cars (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  make text NOT NULL CHECK (char_length(btrim(make)) BETWEEN 1 AND 40),
  model text NOT NULL CHECK (char_length(btrim(model)) BETWEEN 1 AND 40),
  trim text NOT NULL CHECK (char_length(btrim(trim)) BETWEEN 1 AND 80),
  year integer NOT NULL CHECK (year BETWEEN 1900 AND 2100),
  price_cents integer NOT NULL CHECK (price_cents BETWEEN 1 AND 999999999),
  mileage integer NOT NULL CHECK (mileage BETWEEN 0 AND 2999999),
  favorite boolean NOT NULL DEFAULT false,
  sample_key text UNIQUE
);
